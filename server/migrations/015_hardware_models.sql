CREATE TABLE model_families (
  key text PRIMARY KEY CHECK (length(key) BETWEEN 1 AND 40),
  code text NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9-]{1,31}$'),
  label_ru text NOT NULL CHECK (length(label_ru) BETWEEN 1 AND 80),
  sort_order integer NOT NULL DEFAULT 100
);

CREATE TABLE hardware_models (
  id text PRIMARY KEY CHECK (id ~ '^[a-z0-9][a-z0-9-]{1,47}$'),
  name_ru text NOT NULL CHECK (length(name_ru) BETWEEN 2 AND 120),
  name_en text NOT NULL CHECK (length(name_en) BETWEEN 2 AND 120),
  category_slug text NOT NULL REFERENCES categories(slug) ON UPDATE CASCADE,
  family text REFERENCES model_families(key),
  gpu_count smallint CHECK (gpu_count BETWEEN 1 AND 1000),
  gpu_model text CHECK (length(gpu_model) <= 60),
  memory_gb integer CHECK (memory_gb BETWEEN 1 AND 100000),
  form_factor text CHECK (form_factor IN ('SXM', 'PCIe', 'NVL', 'OAM', 'rack')),
  pci_ids text[] NOT NULL DEFAULT '{}' CHECK (cardinality(pci_ids) <= 256 AND
    coalesce(array_to_string(pci_ids, ',', '!'), '') ~ '^([0-9a-f]{4}:[0-9a-f]{4}(,|$))*$'),
  status text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'PENDING', 'DISABLED')),
  source text[] NOT NULL DEFAULT '{}',
  proposed_by uuid REFERENCES users(id),
  proposed_at timestamptz,
  approved_at timestamptz,
  sort_order integer NOT NULL DEFAULT 1000,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  search_words text[] GENERATED ALWAYS AS (market_search_words(name_ru) || market_search_words(name_en)) STORED
);
CREATE UNIQUE INDEX hardware_models_name_unique ON hardware_models (lower(name_ru));
CREATE INDEX hardware_models_category_idx ON hardware_models (category_slug, sort_order) WHERE status = 'ACTIVE';
CREATE INDEX hardware_models_pci_idx ON hardware_models USING gin (pci_ids);
CREATE INDEX hardware_models_pending_owner_idx ON hardware_models (proposed_by) WHERE status = 'PENDING';

CREATE TABLE hardware_model_aliases (
  model_id text NOT NULL REFERENCES hardware_models(id) ON DELETE CASCADE,
  alias text NOT NULL CHECK (length(alias) BETWEEN 1 AND 80),
  words text[] GENERATED ALWAYS AS (market_search_words(alias)) STORED,
  PRIMARY KEY (model_id, alias)
);
CREATE INDEX hardware_model_aliases_words_idx ON hardware_model_aliases USING gin (words);

CREATE TABLE model_analog_groups (
  id text PRIMARY KEY CHECK (id ~ '^[a-z0-9][a-z0-9-]{1,63}$'),
  family_code text NOT NULL REFERENCES model_families(code),
  category_slug text NOT NULL REFERENCES categories(slug) ON UPDATE CASCADE,
  rack boolean NOT NULL DEFAULT false
);
CREATE TABLE model_analog_group_members (
  group_id text NOT NULL REFERENCES model_analog_groups(id) ON DELETE CASCADE,
  model_id text NOT NULL REFERENCES hardware_models(id) ON DELETE CASCADE,
  PRIMARY KEY (group_id, model_id)
);
CREATE INDEX model_analog_group_members_model_idx ON model_analog_group_members (model_id);

ALTER TABLE listings
  ADD COLUMN model_id text REFERENCES hardware_models(id),
  ADD COLUMN analog_model_ids text[] NOT NULL DEFAULT '{}' CHECK (cardinality(analog_model_ids) <= 10),
  ADD CONSTRAINT listings_analogs_buy_only CHECK (kind = 'BUY' OR cardinality(analog_model_ids) = 0),
  ADD CONSTRAINT listings_analogs_require_model CHECK (model_id IS NOT NULL OR cardinality(analog_model_ids) = 0);
CREATE INDEX listings_model_idx ON listings (model_id) WHERE model_id IS NOT NULL;
CREATE INDEX listings_analogs_idx ON listings USING gin (analog_model_ids);

